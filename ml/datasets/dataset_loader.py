from pathlib import Path

import numpy as np
import rasterio
from rasterio.enums import Resampling
import torch


DEFAULT_SCALE = 4
DEFAULT_HR_TILE_SIZE = 64


def create_lr_hr_pairs(
    raster_path: str | Path,
    output_dir: str | Path,
    hr_tile_size: int = DEFAULT_HR_TILE_SIZE,
    scale: int = DEFAULT_SCALE,
) -> list[dict[str, str]]:
    """
    Create LR/HR pairs from a Sentinel-2 raster.

    The input raster is used as the HR reference for the
    pipeline prototype. LR data is generated by controlled
    spatial downsampling.

    Returns:
        List containing paths to generated LR and HR arrays.
    """

    if scale <= 1:
        raise ValueError("scale must be greater than 1.")

    if hr_tile_size <= 0:
        raise ValueError("hr_tile_size must be greater than zero.")

    if hr_tile_size % scale != 0:
        raise ValueError(
            "hr_tile_size must be divisible by scale."
        )

    raster_path = Path(raster_path)
    output_dir = Path(output_dir)

    if not raster_path.exists():
        raise FileNotFoundError(
            f"Raster file does not exist: {raster_path}"
        )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    lr_tile_size = hr_tile_size // scale
    pairs: list[dict[str, str]] = []

    with rasterio.open(raster_path) as src:
        for row in range(
            0,
            src.height - hr_tile_size + 1,
            hr_tile_size,
        ):
            for col in range(
                0,
                src.width - hr_tile_size + 1,
                hr_tile_size,
            ):
                window = rasterio.windows.Window(
                    col,
                    row,
                    hr_tile_size,
                    hr_tile_size,
                )

                hr = src.read(window=window)

                if hr.shape[1:] != (
                    hr_tile_size,
                    hr_tile_size,
                ):
                    continue

                # Downsample the HR tile by the requested scale.
                lr = src.read(
                    window=window,
                    out_shape=(
                        src.count,
                        lr_tile_size,
                        lr_tile_size,
                    ),
                    resampling=Resampling.average,
                ).astype(np.float32)

                hr = hr.astype(np.float32)

                pair_index = len(pairs)

                hr_path = (
                    output_dir
                    / f"sample_{pair_index:05d}_hr.npy"
                )

                lr_path = (
                    output_dir
                    / f"sample_{pair_index:05d}_lr.npy"
                )

                np.save(hr_path, hr)
                np.save(lr_path, lr)

                pairs.append(
                    {
                        "lr": str(lr_path),
                        "hr": str(hr_path),
                    }
                )

    return pairs

class SentinelDataset(torch.utils.data.Dataset):
    """Dataset interface for Sentinel-2 LR/HR samples for PyTorch."""

    def __init__(
        self,
        pairs: list[dict[str, str]],
        augment: bool = False,
    ) -> None:
        self.pairs = pairs
        self.augment = augment

        if not pairs:
            raise ValueError(
                "Dataset cannot be initialized with no pairs."
            )

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, index: int) -> dict[str, torch.Tensor]:
        if index < 0 or index >= len(self.pairs):
            raise IndexError(
                f"Dataset index out of range: {index}"
            )

        pair = self.pairs[index]

        lr = np.load(pair["lr"]).astype(
            np.float32,
            copy=False,
        )

        hr = np.load(pair["hr"]).astype(
            np.float32,
            copy=False,
        )

        if lr.ndim != 3 or hr.ndim != 3:
            raise ValueError(
                "LR and HR samples must have shape "
                "(bands, height, width)."
            )

        if lr.shape[0] != hr.shape[0]:
            raise ValueError(
                "LR and HR must contain the same number of bands."
            )

        # Data augmentation
        if self.augment:
            # Random horizontal flip
            if np.random.rand() > 0.5:
                lr = np.flip(lr, axis=2).copy()
                hr = np.flip(hr, axis=2).copy()
            # Random vertical flip
            if np.random.rand() > 0.5:
                lr = np.flip(lr, axis=1).copy()
                hr = np.flip(hr, axis=1).copy()
            # Random rotation (90, 180, 270)
            k = np.random.randint(0, 4)
            if k > 0:
                lr = np.rot90(lr, k, axes=(1, 2)).copy()
                hr = np.rot90(hr, k, axes=(1, 2)).copy()

        return {
            "lr": torch.from_numpy(lr),
            "hr": torch.from_numpy(hr),
        }